import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import Link from "next/link";
import "./globals.css";

import BotaoAcao from "@/components/BotaoAcao";
import { sair } from "./login/actions";
import { usuarioAtual } from "@/lib/autorizacao";
import { MENU_PRINCIPAL } from "@/lib/permissoes";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  // O menu é montado a partir das permissões do usuário logado.
  // Sem sessão (tela de login), nenhum link aparece.
  const usuario = await usuarioAtual();
  const itensDoMenu = usuario
    ? MENU_PRINCIPAL.filter((item) => usuario.permissoes.has(item.permissao))
    : [];

  return (
    <html
      lang="pt-BR"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        {usuario && (
          <header className="border-b border-zinc-200">
            <nav className="mx-auto flex h-14 w-full max-w-3xl items-center gap-5 overflow-x-auto px-4">
              {itensDoMenu.map((item) => (
                <Link
                  key={item.href}
                  href={item.href}
                  className="shrink-0 text-base font-semibold text-zinc-900"
                >
                  {item.rotulo}
                </Link>
              ))}

              <form action={sair} className="ml-auto shrink-0">
                <BotaoAcao
                  carregando="Saindo..."
                  className="text-base font-medium text-zinc-600"
                >
                  Sair
                </BotaoAcao>
              </form>
            </nav>
          </header>
        )}
        {children}
      </body>
    </html>
  );
}
